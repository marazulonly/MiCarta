/**
 * Converts a TemplateDesignLayer into a backward-compatible MenuTemplate
 */
export function templateDesignLayerToMenuTemplate(layer: TemplateDesignLayer): MenuTemplate {
  return {
    id: layer.id,
    name: layer.name,
    description: layer.description,
    category: layer.category,
    themeStyle: layer.category === 'GOURMET_PREMIUM' ? 'luxury-gold'
      : layer.category === 'CLASICO_VINTAGE' ? 'marine-parchment'
      : layer.category === 'EDITORIAL_MODERNO' ? 'editorial-zigzag'
      : layer.category === 'MINIMALISTA' ? 'minimalist'
      : 'custom',
    fontDisplay: layer.fontDisplay,
    primaryColor: layer.primaryColor,
    darkBgColor: layer.darkBgColor,
    cardBgColor: layer.cardBgColor,
    buttonColor: layer.buttonColor,
    buttonTextColor: layer.buttonTextColor,
    textColor: layer.textColor,
    cardBorderRadius: layer.cardBorderRadius,
    cardStyle: layer.cardStyle,
    headerStyle: layer.headerStyle,
    layoutMode: layer.layoutMode,
    thumbnailUrl: layer.thumbnailUrl,
    badge: layer.badge,
    tags: layer.tags,
    isCustomizable: layer.isCustomizable,
    activeRestaurantsCount: layer.activeRestaurantsCount || 0,
    canvasElements: layer.canvasElements,
    canvasConfig: layer.canvasConfig,
    designLayer: layer,
  };
}

/**
 * Extracts a TemplateDesignLayer from a MenuTemplate
 */
export function menuTemplateToDesignLayer(template: MenuTemplate): TemplateDesignLayer {
  if (template.designLayer) {
    return template.designLayer;
  }
  return {
    id: template.id,
    name: template.name,
    description: template.description,
    category: (template.category as any) || 'CUSTOM',
    thumbnailUrl: template.thumbnailUrl,
    badge: template.badge || 'Plantilla',
    tags: template.tags || [],
    fontDisplay: template.fontDisplay,
    primaryColor: template.primaryColor,
    darkBgColor: template.darkBgColor,
    cardBgColor: template.cardBgColor,
    buttonColor: template.buttonColor,
    buttonTextColor: template.buttonTextColor,
    textColor: template.textColor,
    cardBorderRadius: template.cardBorderRadius,
    cardStyle: template.cardStyle,
    headerStyle: template.headerStyle,
    layoutMode: template.layoutMode || 'grid',
    canvasElements: template.canvasElements,
    canvasConfig: template.canvasConfig,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    isCustomizable: template.isCustomizable,
    activeRestaurantsCount: template.activeRestaurantsCount || 0,
  };
}

/**
 * Initial Menu Templates generated directly from the visual design layers
 */
export const VISUAL_MENU_TEMPLATES: MenuTemplate[] = VISUAL_TEMPLATES_DESIGN_LAYERS.map(templateDesignLayerToMenuTemplate);
